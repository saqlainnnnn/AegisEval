from __future__ import annotations

from enum import Enum
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field

from app.schemas.common import IdentifiableModel


class ModelType(str, Enum):
    """
    Supported AI system types.
    """

    RAG = "rag"
    AGENT = "agent"
    LLM = "llm"
    VISION = "vision"
    MULTIMODAL = "multimodal"
    CUSTOM = "custom"


class ModelConfig(BaseModel):
    """
    Configuration describing the evaluated AI system.
    """

    model_config = ConfigDict(from_attributes=True)

    name: str

    version: str

    model_type: ModelType

    embedding_model: str | None = None

    prompt_version: str | None = None

    retriever: str | None = None

    chunk_size: int | None = None

    top_k: int | None = None

    metadata: dict[str, str] = Field(default_factory=dict)


class Prediction(BaseModel):
    """
    Prediction generated by an AI system.
    """

    model_config = ConfigDict(from_attributes=True)

    question_id: UUID

    answer: str

    retrieved_sources: list[str] = Field(default_factory=list)

    latency_ms: float

    token_usage: int | None = None

    estimated_cost: float | None = None

    metadata: dict[str, str] = Field(default_factory=dict)


class EvaluationResult(IdentifiableModel):
    """
    Stores the output of a benchmark execution.
    """

    model: ModelConfig

    dataset_id: UUID

    predictions: list[Prediction] = Field(default_factory=list)